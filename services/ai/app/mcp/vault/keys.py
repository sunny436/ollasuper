"""Where the encryption key comes from, and how a version becomes an AES key.

NO SECRET MANAGER EXISTS IN THIS DEPLOYMENT. `OPENROUTER_API_KEY` lives in
`services/ai/.env` (0600), written by an operator, never generated by a script
and never defaulted — `deploy/54-ai-service.sh` hard-fails until it is filled in.
This follows that precedent exactly rather than inventing infrastructure:

    MCP_CREDENTIAL_KEYS               {"1": "<base64 32 bytes>", "2": "..."}
    MCP_CREDENTIAL_ACTIVE_KEY_VERSION 2

FAIL CLOSED, NEVER A DEFAULT KEY. A generated-on-boot key would encrypt
credentials that no later process could read, and a hardcoded one would be no
encryption at all. If the vault is enabled and unkeyed, credential operations
raise — loudly, at the point of use.

HKDF, NOT THE RAW ENV VALUE. The env var is a MASTER key; each version derives
its own AES key through HKDF-SHA256 with a fixed salt and a per-version info
label. Two reasons, both small and both real: a future second purpose can derive
its own subkey from the same master instead of reusing this one, and the derived
key is a uniform 32 bytes even if an operator supplies more entropy than that.

KEY ROTATION is lazy (see `store.py`): encrypt with the active version, decrypt
with any version still present. A version is retirable once no stored row names
it — and retiring one makes every row that still names it permanently
unreadable, which is why it is a deliberate operator step, not a cleanup.
"""

from __future__ import annotations

import base64
import binascii
import json

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

__all__ = ["KeyProvider", "VaultKeyError"]

#: Domain separation for HKDF. Constant for the life of the envelope format;
#: changing it makes every stored ciphertext undecryptable.
_HKDF_SALT = b"ollasuper.mcp.credentials.v1"
_KEY_BYTES = 32  # AES-256
#: A master shorter than the derived key has less entropy than it appears to.
_MIN_MASTER_BYTES = 32


class VaultKeyError(RuntimeError):
    """The key material is missing, malformed, or names an unknown version."""


class KeyProvider:
    """Master key material, resolved to per-version AES keys.

    Holds raw key bytes for the life of the process. That is unavoidable — the
    whole point is to decrypt — but it is confined to this object, which is
    constructed once in the lifespan and never logged: `__repr__` is overridden
    below precisely because a dataclass-style repr would print the keys.
    """

    def __init__(self, keys_json: str, active_version: int) -> None:
        parsed = self._parse(keys_json)
        if not parsed:
            raise VaultKeyError(
                "MCP_CREDENTIAL_KEYS is empty; credential encryption cannot "
                "start without key material (fail closed, never a default key)"
            )
        if active_version not in parsed:
            raise VaultKeyError(
                f"MCP_CREDENTIAL_ACTIVE_KEY_VERSION={active_version} is not "
                f"present in MCP_CREDENTIAL_KEYS (have: {sorted(parsed)})"
            )
        self._masters = parsed
        self._active = active_version
        self._derived: dict[int, bytes] = {}

    @staticmethod
    def _parse(keys_json: str) -> dict[int, bytes]:
        if not keys_json or not keys_json.strip():
            return {}
        try:
            raw = json.loads(keys_json)
        except ValueError as exc:
            raise VaultKeyError("MCP_CREDENTIAL_KEYS is not valid JSON") from exc
        if not isinstance(raw, dict):
            raise VaultKeyError(
                'MCP_CREDENTIAL_KEYS must be a JSON object like {"1": "<base64>"}'
            )
        out: dict[int, bytes] = {}
        for version, value in raw.items():
            try:
                number = int(version)
            except (TypeError, ValueError) as exc:
                raise VaultKeyError(
                    f"MCP_CREDENTIAL_KEYS has a non-integer version: {version!r}"
                ) from exc
            if not isinstance(value, str):
                raise VaultKeyError(
                    f"MCP_CREDENTIAL_KEYS: version {number} is not a base64 string"
                )
            try:
                material = base64.b64decode(value, validate=True)
            except (binascii.Error, ValueError) as exc:
                raise VaultKeyError(
                    f"MCP_CREDENTIAL_KEYS: version {number} is not valid base64"
                ) from exc
            if len(material) < _MIN_MASTER_BYTES:
                # The message names the LENGTH, never the value.
                raise VaultKeyError(
                    f"MCP_CREDENTIAL_KEYS: version {number} is {len(material)} bytes; "
                    f"at least {_MIN_MASTER_BYTES} are required"
                )
            out[number] = material
        return out

    @property
    def active_version(self) -> int:
        return self._active

    @property
    def known_versions(self) -> tuple[int, ...]:
        return tuple(sorted(self._masters))

    def key_for(self, version: int) -> bytes:
        """The AES key for one version. Raises for an unknown version.

        Raising rather than returning None is deliberate: an unknown version
        means the envelope was written by a key this deployment no longer has,
        and silently treating that as "decryption failed" would hide a
        configuration mistake behind what looks like tampering.
        """
        cached = self._derived.get(version)
        if cached is not None:
            return cached
        master = self._masters.get(version)
        if master is None:
            raise VaultKeyError(
                f"no key material for version {version}; known versions are "
                f"{list(self.known_versions)}"
            )
        derived = HKDF(
            algorithm=hashes.SHA256(),
            length=_KEY_BYTES,
            salt=_HKDF_SALT,
            info=f"key/{version}".encode(),
        ).derive(master)
        self._derived[version] = derived
        return derived

    def active_key(self) -> tuple[int, bytes]:
        return self._active, self.key_for(self._active)

    def __repr__(self) -> str:  # pragma: no cover - trivial
        # Explicit, because the default would render the key bytes.
        return (
            f"KeyProvider(active={self._active}, "
            f"versions={list(self.known_versions)})"
        )
